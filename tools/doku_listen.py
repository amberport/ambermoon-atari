BEZEICHNER = re.compile(r"(?<![\w.$@])[A-Za-z_][A-Za-z0-9_]*")
MARKE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)(:?)(.*)$")
ZIERDE = re.compile(r"^[\s;*=\-#~]*$")


def lesen(pfad):
    with open(pfad, "rb") as f:
        return f.read().decode("latin-1").splitlines()


def ohne_kommentar(zeile):
    """Statement part of a line: no comment, no quoted strings."""
    if zeile[:1] == "*":
        return ""
    aus, in_text = [], None
    for z in zeile:
        if in_text:
            if z == in_text:
                in_text = None
            continue
        if z in "'\"":
            in_text = z
            continue
        if z == ";":
            break
        aus.append(z)
    return "".join(aus)


def thalion_dateien():
    dateien = []
    for wurzel, _, namen in os.walk(URCODE):
        for n in namen:
            if n.upper().endswith(".S"):
                rel = os.path.relpath(os.path.join(wurzel, n), URCODE)
                dateien.append(rel.replace(os.sep, "/"))
    return sorted(dateien)


def eigene_dateien():
    dateien = list(EIGENE)
    for ordner in EIGENE_ORDNER:
        for wurzel, _, namen in os.walk(os.path.join(WURZEL, ordner)):
            for n in sorted(namen):
                if n.upper().endswith((".S", ".I")):
                    dateien.append(os.path.relpath(os.path.join(wurzel, n),
                                                   WURZEL))
    return dateien


