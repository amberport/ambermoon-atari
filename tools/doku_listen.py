# ---------------------------------------------------------------- appendix B

def thalion_namen():
    """(defined, references): what Thalion's engine files define at column 0
    and how often each identifier occurs in their statements (lines)."""
    definiert, bezug, dateien = set(), {}, {}
    for d in thalion_dateien():
        if d in NICHT_ENGINE:
            continue
        for z in lesen(os.path.join(URCODE, d)):
            m = MARKE.match(z)
            if m:
                definiert.add(m.group(1))
            rumpf = ohne_kommentar(z)
            if m:
                rumpf = rumpf[len(m.group(1)) + len(m.group(2)):]
            for name in set(BEZEICHNER.findall(rumpf)):
                bezug[name] = bezug.get(name, 0) + 1
                dateien.setdefault(name, set()).add(d)
    return definiert, bezug, dateien


def art_von(rumpf, abschnitt):
    teile = rumpf.split()
    wort = teile[0].lower() if teile else ""
    if wort in ("equ", "=", "set") or rumpf.lstrip().startswith("="):
        return "constant"
    if wort == "macro":
        return "macro"
    if wort.startswith("rs"):
        return "offset"
    if wort.startswith(("ds", "dcb")):
        return "variable" if abschnitt == "bss" else "data"
    if wort.startswith(("dc", "incbin")):
        return "data"
    if abschnitt == "bss":
        return "variable"
    if abschnitt == "data":
        return "data"
    return "routine"


def _kopfzeile(block, name):
    """'Name -- text' (also 'A, Name, B -- text') in a comment block."""
    for k, b in enumerate(block):
        m = re.match(r"([\w ,/]+?)\s*(?:--|—|:)\s*(.*)", b)
        if not m or name not in re.split(r"[\s,/]+", m.group(1)):
            continue
        teile = [m.group(2)]
        for weiter in block[k + 1:]:
            if not weiter or ZIERDE.match(weiter) or teile[-1].endswith("."):
                break
            teile.append(weiter)
        return " ".join(teile)
    return ""


def kopfblock(zeilen, i):
    """The comment block right above line i (a header may serve several
    labels in a row; blank lines between header and label are skipped)."""
    j = i - 1
    while j >= 0 and (MARKE.match(zeilen[j]) and not
                      ohne_kommentar(zeilen[j]).split(":", 1)[-1].strip()
                      or not zeilen[j].strip()):
        j -= 1                          # labels sharing the header, blanks
    block = []
    while j >= 0 and zeilen[j].lstrip().startswith(";"):
        block.insert(0, zeilen[j].lstrip()[1:].strip())
        j -= 1
    return block


# The register contract in a header (docs/developer/04-interface.md,
# "Writing a routine of the library"):
#   ; Name -- one sentence.
#   ;   IN : d0.w = line, a0 = source
#   ;   OUT: d0.w = bank offset
#   ;   All other registers are preserved.     (or: Changes d0-d2/a0.)
# The German forms of older headers count too.
SCHLUESSEL = re.compile(r"^(IN|OUT)\s*:\s*(.*)$")
ALLE_UEBRIGEN = re.compile(r"Alle uebrigen Register bleiben|All other "
                           r"registers are preserved", re.I)
ALLE = re.compile(r"Alle Register bleiben|All registers are preserved|"
                  r"Rettet alle Register|Saves all registers|Alle Register werden "
                  r"erhalten", re.I)
AENDERT = re.compile(r"(?:Veraendert|Changes|Destroys)\s+([ad][0-7]"
                     r"(?:[-/,][ad]?[0-7])*)", re.I)


def register(zeilen, i, name):
    """The register contract from the header above line i, or ''.  Only
    the explicit forms above count; a description in prose stays out
    (better none than a wrong one)."""
    def namenszeile(block):
        for k, b in enumerate(block):     # the part of the header for name
            m = re.match(r"([\w ,/]+?)\s*(?:--|—)\s*", b)
            if m and name in re.split(r"[\s,/]+", m.group(1)):
                return k
        return None

    block = kopfblock(zeilen, i)
    anfang = namenszeile(block) or 0
    if not block:
        # a label behind another routine's code: its header stands
        # elsewhere in the file ('Name -- ...'), as vertrag() finds it
        for k, z in enumerate(zeilen):
            if z.lstrip().startswith(";") and (k == 0 or not
                                               zeilen[k - 1].lstrip().startswith(";")):
                kandidat = []
                for w in zeilen[k:]:
                    if not w.lstrip().startswith(";"):
                        break
                    kandidat.append(w.lstrip()[1:].strip())
                n = namenszeile(kandidat)
                if n is not None:
                    block, anfang = kandidat, n
                    break
    teil = []
    for b in block[anfang:]:          # up to the next '****' line
        if teil and b and ZIERDE.match(b):
            break
        teil.append(b)
    felder, aktiv = {}, None
    for b in teil:
        m = SCHLUESSEL.match(b)
        if m:
            aktiv = m.group(1).lower()
            felder[aktiv] = [m.group(2)]
        elif aktiv and b and not ZIERDE.match(b):
            felder[aktiv].append(b)
        else:
            aktiv = None
    text = " ".join(teil)
    teile = []
    for k in ("in", "out"):
        if k in felder:
            f = " ".join(felder[k])
            f = ALLE_UEBRIGEN.sub("", ALLE.sub("", f)).strip(" .")
            f = AENDERT.sub("", f).strip(" .")
            if f:
                teile.append(f"{k}: {f}")
    if ALLE_UEBRIGEN.search(text):
        teile.append("other registers preserved")
    elif ALLE.search(text):
        teile.append("all registers preserved")
    else:
        m = AENDERT.search(text)
        if m:
            teile.append(f"changes {m.group(1)}")
    text = re.sub(r"\s+", " ", "; ".join(teile)).replace("|", "\\|")
    return text if len(text) <= 200 else text[:197].rstrip() + "..."


def vertrag(zeilen, i, name):
    """Our one-line description of a name, or '' (better none than a wrong
    one): 'Name -- ...' or 'Name: ...' in the header above (a header may
    serve several labels in a row), else the comment on the label's own
    line ('Name: ds.b 1 ; ...'), else 'Name -- ...' anywhere in the file.
    Headers in the form '; Name -- one sentence.' therefore show up here."""
    block = kopfblock(zeilen, i)
    text = _kopfzeile(block, name)
    if not text and ";" in zeilen[i]:
        rumpf = ohne_kommentar(zeilen[i]).split(":", 1)[-1].strip()
        if rumpf and not rumpf.split()[0].lower() in ("bra", "rts", "jmp"):
            text = zeilen[i].split(";", 1)[1].strip()   # 'Name: ds.b 1 ; ...'
    if not text:
        alle = [z.lstrip()[1:].strip() for z in zeilen
                if z.lstrip().startswith(";")]
        text = _kopfzeile(alle, name)
    text = re.sub(r"\s+", " ", text).replace("|", "\\|")
    return text if len(text) <= 140 else text[:137].rstrip() + "..."


def eigene_namen():
    """name -> list of (file, line, kind, description), ours and generated."""
    namen = {}
    quellen = [(p, False) for p in eigene_dateien()] + \
              [(p, True) for p in GEBAUT if os.path.exists(os.path.join(WURZEL, p))]
    for pfad, gebaut in quellen:
        zeilen = lesen(os.path.join(WURZEL, pfad))
        abschnitt = "code"
        for i, z in enumerate(zeilen):
            s = re.match(r"\s+SECTION\s+\w+\s*,\s*(\w+)", z, re.I)
            if s:
                abschnitt = s.group(1).lower()
                continue
            m = MARKE.match(z)
            if not m:
                continue
            name, rumpf = m.group(1), ohne_kommentar(m.group(3))
            if name.upper() in ("IFD", "IFND", "ELSE", "ENDC", "IF", "ENDM"):
                continue
            if not rumpf.strip():
                # label alone on its line: the next statement decides
                for nz in zeilen[i + 1:i + 6]:
                    if ohne_kommentar(nz).strip():
                        rumpf = ohne_kommentar(nz)
                        break
            art = art_von(rumpf, abschnitt)
            if pfad.endswith("textmarken.i") or pfad.endswith("intro_daten.i"):
                art = "text"
            if pfad.endswith("AM2_CPU_STUBS.S"):
                art += " (placeholder)"
            text = GEBAUT_HERKUNFT[pfad] if gebaut else vertrag(zeilen, i, name)
            reg = "" if gebaut or not art.startswith("routine") \
                else register(zeilen, i, name)
            namen.setdefault(name, []).append((pfad, i + 1, art, text, reg))
    return namen


REGISTER_TEXT = (
    "*Registers* is the contract as our header states it: *in* and *out* "
    "as the routine's `IN :` and `OUT:` lines say, then what survives. "
    "Empty means the header does not state it in that form; then read the "
    "call sites and the routine (chapter 4, \"Where to find a contract\"). "
    "The contract is AM2_CPU's: Thalion's callers rely on it.\n\n")


def anhang_b():
    definiert, bezug, dateien = thalion_namen()
    eigen = eigene_namen()
    schnitt = sorted((n for n in eigen if n in bezug and n not in definiert),
                     key=str.lower)
    gruppen = {"routine": [], "data": [], "constant": [], "macro": []}
    for n in schnitt:
        art = eigen[n][0][2]
        if art.startswith("routine"):
            gruppen["routine"].append(n)
        elif art.startswith(("constant", "offset")):
            gruppen["constant"].append(n)
        elif art.startswith("macro"):
            gruppen["macro"].append(n)
        else:
            gruppen["data"].append(n)

    def ort(n):
        pfad, zeile = eigen[n][0][:2]
        mehr = f" (+{len(eigen[n]) - 1})" if len(eigen[n]) > 1 else ""
        return f"`{pfad}:{zeile}`{mehr}"

    zeilen = [KOPF, "# Appendix B: the interface between Thalion's code and "
              "our layer\n\n",
              "Every name that Thalion's engine files (all except "
              "`FAIRY.S`) use **without defining it**, and where our side "
              "defines it. In the original these names came from `AM2_CPU` "
              "and from Thalion's unreleased include file. *Uses* counts the "
              "lines in Thalion's files that mention the name, *files* the "
              "files. *Defined in* is the first definition; `(+n)` means n "
              "more, usually a Falcon and an ST variant under `IFD "
              "ZIEL_ST`. Descriptions are our own header comments, some "
              "still German (they are translated as they change).\n\n",
              f"In total: {len(schnitt)} names; "
              f"{len(gruppen['routine'])} routines, "
              f"{len(gruppen['data'])} data and variables, "
              f"{len(gruppen['constant'])} constants and offsets, "
              f"{len(gruppen['macro'])} macros.\n\n"]
    titel = {"routine": "Routines", "data": "Data and variables",
             "constant": "Constants and structure offsets",
             "macro": "Macros"}
    for gruppe in ("routine", "data", "macro", "constant"):
        mit_reg = gruppe == "routine"
        zeilen += [f"## {titel[gruppe]}\n\n"]
        if mit_reg:
            zeilen.append(REGISTER_TEXT)
        zeilen += ["| Name | Kind | Defined in | Uses | Files | Description |"
                   + (" Registers |" if mit_reg else "") + "\n",
                   "|---|---|---|---:|---:|---|" + ("---|" if mit_reg else "")
                   + "\n"]
        for n in gruppen[gruppe]:
            _, _, art, text, reg = eigen[n][0]
            zeilen.append(f"| `{n}` | {art} | {ort(n)} | {bezug[n]} | "
                          f"{len(dateien[n])} | {text} |"
                          + (f" {reg} |" if mit_reg else "") + "\n")
        zeilen.append("\n")

    # Names Thalion uses that nobody defines would fail the link; names
    # Thalion defines that we define too are what einheiten_verbinden.py
    # guards.  Here only a count of our own routines outside the interface.
    intern = sorted((n for n in eigen
                     if n not in bezug and eigen[n][0][2] == "routine"
                     and n[:1].isupper()
                     and not eigen[n][0][0].startswith("build/")),
                    key=str.lower)
    zeilen += ["## Our internal routines\n\n",
               "Routines of our layer that Thalion's code does not call "
               "(capitalised names; lower-case labels are local helpers and "
               "not listed).\n\n",
               "| Name | Defined in | Description | Registers |\n",
               "|---|---|---|---|\n"]
    for n in intern:
        zeilen.append(f"| `{n}` | {ort(n)} | {eigen[n][0][3]} | "
                      f"{eigen[n][0][4]} |\n")
    return "".join(zeilen)


