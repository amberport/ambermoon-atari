def einbindungen(einheit):
    """Thalion files a unit includes: INCLUDE "X" without src/ and not .i."""
    gefunden = []
    for z in lesen(os.path.join(WURZEL, "engine", einheit)):
        m = re.match(r'\s+INCLUDE\s+"([^"]+)"', z, re.I)
        if m and not m.group(1).startswith("src/") \
                and not m.group(1).lower().endswith(".i"):
            gefunden.append(m.group(1))
    return gefunden


